def detect_mode(text):
    t = text.lower().strip()

    # ПРОГРАММИРОВАНИЕ
    code_words = [
        "напиши код",
        "покажи код",
        "исправь код",
        "код",
        "python",
        "javascript",
        "html",
        "css",
        "программирование",
        "программировать",
        "ошибка в коде",
        "api",
        "github",
        "telegram bot",
        "телеграм бот",
        "бота",
    ]

    if any(word in t for word in code_words):
        return "code"

    # ДЕНЬГИ / БИЗНЕС
    strategy_words = [
        "как заработать",
        "как заработать деньги",
        "как начать зарабатывать",
        "как зарабатывать",
        "заработок",
        "деньги",
        "бизнес",
        "стартап",
        "доход",
        "инвестиции",
        "инвестировать",
        "клиенты",
        "продажи",
        "монетизация",
        "карьера",
        "как сделать бизнес",
        "как найти клиентов",
    ]

    if any(word in t for word in strategy_words):
        return "strategy"

    # ЯВНЫЕ ЗАПРОСЫ ПРО ЦЕЛИ
    goal_words = [
        "моя цель",
        "как достичь цели",
        "как добиться цели",
        "как достичь",
        "как добиться",
        "план действий",
        "что мне делать дальше",
        "как изменить свою жизнь",
        "хочу изменить свою жизнь",
        "хочу всё изменить",
        "хочу начать с нуля",
    ]

    if any(word in t for word in goal_words):
        return "strategy"

    # АНАЛИЗ СИТУАЦИИ
    analysis_words = [
        "поссорился",
        "поссорилась",
        "конфликт",
        "ситуация",
        "как поступить",
        "как мне поступить",
        "не знаю что делать",
        "что мне делать",
        "как разобраться",
        "помоги разобраться",
        "меня бесит",
        "меня раздражает",
    ]

    if any(word in t for word in analysis_words):
        return "analysis"

    return "chat"


def build_strategy_context(user):
    parts = []

    goal = user.get("goal", "")
    if goal:
        parts.append(f"Главная цель пользователя: {goal}")

    dreams = user.get("dreams", [])
    if dreams:
        parts.append(
            "Последняя мечта/желание: " + dreams[-1][:500]
        )

    wins = user.get("wins", [])
    if wins:
        parts.append(
            "Последняя победа: " + wins[-1][:500]
        )

    mistakes = user.get("mistakes", [])
    if mistakes:
        parts.append(
            "Последняя трудность: " + mistakes[-1][:500]
        )

    return "\n".join(parts)


def chat_ai(text, memory, user, internet_context=""):
    try:
        mode = detect_mode(text)

        messages = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT
            }
        ]

        # --------------------------------------------------
        # КОНТЕКСТ ПРОШЛОГО РАЗГОВОРА
        # --------------------------------------------------

        recent = memory[-3:]

        for msg in recent:
            if not msg:
                continue

            if msg.strip() == text.strip():
                continue

            messages.append({
                "role": "user",
                "content": msg[:600]
            })

        # --------------------------------------------------
        # СТРАТЕГИЧЕСКИЙ РЕЖИМ
        # --------------------------------------------------

        if mode == "strategy":

            strategy = build_strategy(user, text)

            if strategy:
                messages.append({
                    "role": "system",
                    "content": (
                        "Текущий режим: практический стратег.\n"
                        "Используй эти инструкции только для текущего запроса:\n"
                        + strategy[:1600]
                    )
                })

            brain = build_brain(user)

            if brain:
                messages.append({
                    "role": "system",
                    "content": brain[:800]
                })

        # --------------------------------------------------
        # КОД
        # --------------------------------------------------

        elif mode == "code":

            messages.append({
                "role": "system",
                "content": """
Режим разработчика.

Давай конкретное решение.
Если нужен код — дай готовый код.
Если пользователь показал ошибку — найди причину.
Не перегружай ответ ненужной теорией.
"""
            })

        # --------------------------------------------------
        # АНАЛИЗ
        # --------------------------------------------------

        elif mode == "analysis":

            messages.append({
                "role": "system",
                "content": """
Режим анализа ситуации.

Сначала пойми, что происходит.
Не выдумывай детали.
Если информации недостаточно — задай один хороший уточняющий вопрос.
Если информации достаточно — дай честный и практичный взгляд.
"""
            })

        # --------------------------------------------------
        # АКТУАЛЬНАЯ ИНФОРМАЦИЯ
        # --------------------------------------------------

        if internet_context:
            messages.append({
                "role": "system",
                "content": (
                    "Актуальная информация из источников:\n"
                    + internet_context[:2500]
                )
            })

        # --------------------------------------------------
        # ТЕКУЩИЙ ЗАПРОС
        # --------------------------------------------------

        messages.append({
            "role": "user",
            "content": text[:3000]
        })

        response = client.chat.completions.create(
            model="openai/gpt-oss-120b",
            messages=messages,
            temperature=0.72,
            max_tokens=700
        )

        answer = response.choices[0].message.content

        if not answer:
            return "Что-то не получилось ответить. Напиши ещё раз."

        return answer.strip()

    except Exception as e:
        print("ATLAS ERROR:", e)
        return "Что-то пошло не так с ответом. Попробуй ещё раз."