def build_brain(user):
    goal = user.get("goal", "")

    if not goal:
        return ""

    return f"""
Стратегический контекст пользователя.

Главная цель:
{goal}

Помогай двигаться к этой цели только тогда,
когда текущий вопрос действительно связан с ней.

Не притягивай цель к обычному разговору.
Не превращай отдых, скуку, эмоции и обычные вопросы
в разговор о продуктивности.
"""